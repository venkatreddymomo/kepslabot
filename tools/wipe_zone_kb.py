"""
FULL clean wipe of all Zone (hotel code 'zone') property + KB data, so the KB can
be re-uploaded and reindexed from scratch.

WIPES (everything scoped to the Zone hotel id):
  - new_bot_properties          (all property rows)
  - new_bot_kb_books            (all, incl. shared property_id IS NULL)
  - new_bot_kb_pages            (all)
  - new_bot_kb_book_pages       (all links for the above)
  - bot_hotel_images_scraper    (all images, incl. hotel-level NULL-property ones)
  - new_bot_kb_files            (all raw uploaded source files)
  - resets the KB/property-derived fields of json_section.business +
    json_section.knowledge_base (manifest, counts, sources list, library_index)
    so a reindex starts clean and won't read dead source refs.

DOES NOT TOUCH (reused after re-add + reindex):
  - new_bot_services            (services + their config/prompts)
  - json_section.service_kb     (regenerated by reindex's enrich step)
  - new_bot_widget_deployments  (widget embed + theme)
  - new_bot_prompt_registry     (the de-hardcoded prompts)
  - ticketing config / settings / .env
  - hotel-level business config (name, bot_name, contact, channels, departments,
    escalation, faq_bank, tools, ui_settings, journey_phases)
  - operational data: sessions, conversations, messages, tickets, leads, logs

Dry-run by default — nothing is written until --apply.
    python tools/wipe_zone_kb.py            # DRY RUN
    python tools/wipe_zone_kb.py --apply
"""
from __future__ import annotations

import asyncio
import json
import sys

from sqlalchemy import delete, func, select, text

from models.database import (
    AsyncSessionLocal, Hotel, ImageAsset, KBBook, KBFile, KBPage, Property, engine,
)

HOTEL_CODE = "zone"


async def _scalar(s, stmt, params=None):
    return int((await s.execute(text(stmt), params or {})).scalar() or 0)


def _reset_business(b: dict) -> dict:
    b["multi_property_location_manifest"] = []
    b["property_count"] = 0
    b["location_count"] = 0
    b["multi_property_welcome_message"] = ""
    return b


def _reset_kb(kb: dict) -> dict:
    kb["sources"] = []
    kb["expected_property_count"] = 0
    kb["library_index"] = {}
    return kb


async def _load_blob(s, hid, key):
    row = (await s.execute(text(
        "SELECT config_value FROM new_bot_business_config WHERE hotel_id=:h AND config_key=:k"
    ), {"h": hid, "k": key})).first()
    return json.loads(row[0]) if row and row[0] else None


async def _save_blob(s, hid, key, obj):
    await s.execute(text(
        "UPDATE new_bot_business_config SET config_value=:v WHERE hotel_id=:h AND config_key=:k"
    ), {"v": json.dumps(obj, ensure_ascii=False), "h": hid, "k": key})


async def main(apply: bool) -> int:
    print(f"DB: {engine.url.render_as_string(hide_password=True)}")
    print("Mode: " + ("APPLY (will DELETE)" if apply else "DRY RUN (no writes)"))
    print("=" * 72)

    async with AsyncSessionLocal() as s:
        hotel = (await s.execute(
            select(Hotel).where(func.lower(Hotel.code) == HOTEL_CODE)
        )).scalar_one_or_none()
        if hotel is None:
            print(f"No hotel with code '{HOTEL_CODE}'. Aborting.")
            return 1
        hid = hotel.id
        print(f"HOTEL id={hid} code={hotel.code!r} name={hotel.name!r}\n")

        nprops = await _scalar(s, "SELECT COUNT(*) FROM new_bot_properties WHERE hotel_id=:h", {"h": hid})
        nbooks = await _scalar(s, "SELECT COUNT(*) FROM new_bot_kb_books WHERE hotel_id=:h", {"h": hid})
        npages = await _scalar(s, "SELECT COUNT(*) FROM new_bot_kb_pages WHERE hotel_id=:h", {"h": hid})
        nimages = await _scalar(s, "SELECT COUNT(*) FROM bot_hotel_images_scraper WHERE hotel_id=:h", {"h": hid})
        nfiles = await _scalar(s, "SELECT COUNT(*) FROM new_bot_kb_files WHERE hotel_id=:h", {"h": hid})
        nlinks = await _scalar(s,
            "SELECT COUNT(*) FROM new_bot_kb_book_pages WHERE book_id IN "
            "(SELECT id FROM new_bot_kb_books WHERE hotel_id=:h) OR page_id IN "
            "(SELECT id FROM new_bot_kb_pages WHERE hotel_id=:h)", {"h": hid})

        print("WILL DELETE:")
        print(f"  new_bot_properties .......... {nprops}")
        print(f"  new_bot_kb_books ............ {nbooks}")
        print(f"  new_bot_kb_pages ............ {npages}")
        print(f"  new_bot_kb_book_pages ....... {nlinks}")
        print(f"  bot_hotel_images_scraper .... {nimages}")
        print(f"  new_bot_kb_files ............ {nfiles}")

        biz = await _load_blob(s, hid, "json_section.business")
        kb = await _load_blob(s, hid, "json_section.knowledge_base")
        print("\nWILL RESET (KB/property-derived fields only):")
        if biz:
            print(f"  json_section.business: property_count {biz.get('property_count')}->0, "
                  f"location_count {biz.get('location_count')}->0, manifest "
                  f"{len(biz.get('multi_property_location_manifest') or [])}->0")
        if kb:
            li = kb.get("library_index", {})
            print(f"  json_section.knowledge_base: sources {len(kb.get('sources') or [])}->0, "
                  f"library_index docs {len(li.get('documents') or [])}->0")
        print("\nWILL NOT TOUCH: services, service_kb, widget, prompts, ticketing, "
              "hotel-level config, sessions/tickets/leads/logs.")

        if not apply:
            print("\nDRY RUN complete. Re-run with --apply to wipe.")
            return 0

        # ---- APPLY (FK-safe order) ----
        await s.execute(text(
            "DELETE FROM new_bot_kb_book_pages WHERE book_id IN "
            "(SELECT id FROM new_bot_kb_books WHERE hotel_id=:h) OR page_id IN "
            "(SELECT id FROM new_bot_kb_pages WHERE hotel_id=:h)"), {"h": hid})
        await s.execute(delete(KBPage).where(KBPage.hotel_id == hid))
        await s.execute(delete(KBBook).where(KBBook.hotel_id == hid))
        await s.execute(delete(ImageAsset).where(ImageAsset.hotel_id == hid))
        await s.execute(delete(Property).where(Property.hotel_id == hid))
        await s.execute(delete(KBFile).where(KBFile.hotel_id == hid))
        if biz:
            await _save_blob(s, hid, "json_section.business", _reset_business(biz))
        if kb:
            await _save_blob(s, hid, "json_section.knowledge_base", _reset_kb(kb))
        await s.commit()

        # verify
        left = await _scalar(s, "SELECT COUNT(*) FROM new_bot_properties WHERE hotel_id=:h", {"h": hid})
        left_files = await _scalar(s, "SELECT COUNT(*) FROM new_bot_kb_files WHERE hotel_id=:h", {"h": hid})
        print(f"\nDONE. properties left={left}, kb_files left={left_files} (expected 0/0).")
        print("Next (you): start server -> upload new KB files -> reindex (clear_existing).")
    await engine.dispose()
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main(apply="--apply" in sys.argv[1:])))
